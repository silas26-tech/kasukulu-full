export function getCurrentTimeCategory(
  date: Date = new Date()
): "morning" | "afternoon" | "evening" | "night" {
  const hour = date.getHours();
  if (hour >= 5 && hour < 12) return "morning";
  if (hour >= 12 && hour < 17) return "afternoon";
  if (hour >= 17 && hour < 21) return "evening";
  return "night";
}

export function getTimeCategoryLabel(
  category: "morning" | "afternoon" | "evening" | "night"
): string {
  switch (category) {
    case "morning":
      return "Morning Greeting (05:00 - 12:00)";
    case "afternoon":
      return "Afternoon Greeting (12:00 - 17:00)";
    case "evening":
      return "Evening Greeting (17:00 - 21:00)";
    case "night":
      return "Good Night Greeting (21:00 - 05:00)";
  }
}

