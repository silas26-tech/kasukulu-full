export function getLanguageById(id: string): LanguageItem | undefined {
  return ALL_GREETINGS_DATA.find((l) => l.id.toLowerCase() === id.toLowerCase());
}

export function getLanguageByLanguageAid(aid: LanguageAid): LanguageItem {
  const match = ALL_GREETINGS_DATA.find((l) => l.languageAidKey === aid);
  if (match) return match;

  const stripped = aid.replace("English + ", "").toLowerCase();
  const directMatch = ALL_GREETINGS_DATA.find(
    (l) => l.name.toLowerCase().includes(stripped) || l.id.toLowerCase() === stripped
  );
  return directMatch ?? ALL_GREETINGS_DATA[0];
}

export function getGreetingForLanguageAndTime(
  languageId: string,
  timeCat: "morning" | "afternoon" | "evening" | "night" = getCurrentTimeCategory()
): GreetingPhrase {
  const lang = getLanguageById(languageId) ?? ALL_GREETINGS_DATA[0];
  const matched =
    lang.greetings.find(
      (g) => g.timeOfDay === timeCat || g.category === timeCat
    ) ??
    (timeCat === "night"
      ? lang.greetings.find(
          (g) => g.timeOfDay === "evening" || g.category === "evening"
        )
      : undefined);
  return matched ?? lang.greetings[0];
}

export function mapLanguageAidToLanguageId(aid: LanguageAid): string {
  switch (aid) {
    case "English Only":
      return "english";
    case "English + Bemba":
      return "bemba";
    case "English + Nyanja":
      return "nyanja";
    case "English + Tonga":
      return "tonga";
    case "English + Lozi":
      return "lozi";
    case "English + Kaonde":
      return "kaonde";
    case "English + Luvale":
      return "luvale";
    case "English + Lunda":
      return "lunda";
    case "English + French":
      return "french";
    case "English + Swahili":
      return "swahili";
    default:
      return "bemba";
  }
}
