export function normalizeLearnerForm(gradeOrForm?: string): OLevelForm {
  const value = (gradeOrForm || '').trim().toLowerCase();
  if (value.includes('1') || value.includes('grade 8')) return 'Form 1';
  if (value.includes('2') || value.includes('grade 9')) return 'Form 2';
  if (value.includes('3') || value.includes('grade 10') || value.includes('grade 11')) {
    return 'Form 3';
  }
  return 'Form 4';
}

export function getEnglishTopicsForLearner(gradeOrForm?: string): FormSyllabusTopic[] {
  const targetForm = normalizeLearnerForm(gradeOrForm);
  return ENGLISH_FORM_1_TO_4_TOPICS.filter((topic) => topic.form === targetForm);
}
